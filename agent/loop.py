"""Agent Zero loop: generate -> compile -> test -> reflect -> export.

The iteration budget is bounded (default 5) and the conversation is rebuilt
from (task, last failure) each round rather than accumulated, so context stays
flat no matter how many iterations run.
"""

import os
import time
from dataclasses import dataclass, field

from .prompts import build_messages
from .sandbox import build_shared_library, execute_sandbox, extract_blocks


@dataclass
class AgentArtifact:
    status: str                       # "SUCCESS" | "FAILED"
    task: str
    lib_path: str = ""
    header_path: str = ""
    example_path: str = ""
    iterations: int = 0
    total_ms: float = 0.0
    solution: str = ""
    last_feedback: str = ""
    history: list = field(default_factory=list)

    def __str__(self):
        if self.status != "SUCCESS":
            return (f"[{self.status}] {self.task!r} after {self.iterations} iteration(s) "
                    f"({self.total_ms:.0f}ms)\n  last: {self.last_feedback[:200]}")
        return (f"[SUCCESS] {self.task!r}\n"
                f"  lib:     {self.lib_path}\n"
                f"  header:  {self.header_path}\n"
                f"  example: {self.example_path}\n"
                f"  iterations: {self.iterations}, total: {self.total_ms:.0f}ms")


EXAMPLE_TEMPLATE = """#!/usr/bin/env python3
\"\"\"Drop-in usage example for {lib_name} (auto-generated by Agent Zero).

Loads the shared library with ctypes using the prototypes from {hdr_name}.

NOTE: the library is built for the host that produced it. ctypes cannot load a
foreign-architecture .so/.dll in-process -- run this on the matching machine,
or wrap the library with the cross loader harness used in
tests/test_c_interop.py.
\"\"\"

import ctypes
import os
import platform

LIB = os.path.join(os.path.dirname(os.path.abspath(__file__)), "{lib_name}")
if not os.path.exists(LIB):
    raise SystemExit(f"missing {{LIB}} -- rebuild with: python aic.py agent ...")

try:
    lib = ctypes.CDLL(LIB)
except OSError as e:
    raise SystemExit(
        f"cannot load {{LIB}} on {{platform.machine()}}: {{e}}\\n"
        "This library targets the architecture it was built for; "
        "run the example on a matching host."
    )
{argtypes}

if __name__ == "__main__":
{CALLS}
    print("OK")
"""


def _header_prototypes(header_text):
    """Parse `int64_t name(int64_t a, int64_t b);` lines from the generated .h."""
    protos = []
    for line in header_text.splitlines():
        line = line.strip()
        if not line.startswith(("int64_t ", "const char*")) or not line.endswith(";"):
            continue
        sig = line[:-1]
        name, args = sig.split("(", 1)
        name = name.split()[-1]
        params = [a.strip() for a in args.split(",") if a.strip()]
        n = len(params)
        protos.append((name, n))
    return protos


def write_example(header_path, example_path, call=None):
    """Write a runnable ctypes example built from the generated .h prototypes.

    `call` is an optional (fn_name, args_tuple) override; otherwise the first
    exported function is called with an argument count matching its signature.
    """
    hdr_name = os.path.basename(header_path)
    lib_name = os.path.splitext(hdr_name)[0] + (".dll" if os.name == "nt" else ".so")
    header_text = open(header_path, encoding="utf-8").read()
    protos = _header_prototypes(header_text)

    argtypes = "\n".join(
        f"lib.{name}.argtypes = [{', '.join(['ctypes.c_int64'] * n)}]\n"
        f"lib.{name}.restype = ctypes.c_int64"
        for name, n in protos
    )

    if call:
        fn, args = call
    elif protos:
        fn, n = protos[0]
        args = tuple(7 for _ in range(n))
    else:
        fn, args = None, ()

    if fn:
        argv = ", ".join(str(a) for a in args)
        calls = f'    print("{fn}({argv}) =", lib.{fn}({argv}))'
    else:
        calls = '    print("no exported functions")'

    with open(example_path, "w", encoding="utf-8") as f:
        f.write(EXAMPLE_TEMPLATE.format(lib_name=lib_name, hdr_name=hdr_name,
                                        argtypes=argtypes, CALLS=calls))
    return example_path


def run_agent_loop(task, out_prefix, max_iterations=5, opt=False, llm_fn=None, verbose=True):
    from .client import make_llm

    llm = llm_fn or make_llm()
    start = time.perf_counter()
    history = []
    feedback = None
    previous = None

    for it in range(1, max_iterations + 1):
        messages = build_messages(task, feedback, previous)
        try:
            reply = llm(messages)
        except Exception as e:  # LLM/network failure is not a compile failure
            if verbose:
                print(f"[Iter {it}/{max_iterations}] LLM FAIL -> {e}")
            return AgentArtifact("FAILED", task, iterations=it,
                                 total_ms=(time.perf_counter() - start) * 1000,
                                 last_feedback=f"LLM error: {e}", history=history)

        solution, test = extract_blocks(reply)
        result = execute_sandbox(solution, test, opt=opt)
        history.append({"iteration": it, "stage": result.stage, "ok": result.success,
                        "compile_ms": result.compile_ms, "run_ms": result.run_ms,
                        "feedback": result.feedback})
        previous = reply
        feedback = result.summary()

        if verbose:
            print(f"[Iter {it}/{max_iterations}] {feedback}")

        if result.success:
            try:
                lib, hdr = build_shared_library(solution, out_prefix,
                                                imports=result.imports, opt=opt)
            except Exception as e:
                # A local toolchain/packaging failure is not something the model
                # can fix by writing different AIC, so do not spend iterations on
                # it -- report it straight away.
                if verbose:
                    print(f"[Iter {it}/{max_iterations}] LIB BUILD FAIL -> {e}")
                return AgentArtifact("FAILED", task, iterations=it,
                                     total_ms=(time.perf_counter() - start) * 1000,
                                     last_feedback=f"library export failed: {e}",
                                     solution=solution, history=history)
            example = write_example(hdr, os.path.splitext(out_prefix)[0] + "_example.py")
            return AgentArtifact("SUCCESS", task, lib, hdr, example, it,
                                 (time.perf_counter() - start) * 1000,
                                 solution=solution, history=history)

    return AgentArtifact("FAILED", task, iterations=max_iterations,
                         total_ms=(time.perf_counter() - start) * 1000,
                         last_feedback=feedback or "", history=history)
